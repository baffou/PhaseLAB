function saveTiffMeta(fileName, Itf, MI, opt)
arguments
    fileName {mustBeText}
    Itf Interfero
    MI (1,1) Microscope
    opt.lambda = []
    opt.RefFileNname {mustBeText} = ''
    opt.expTime = []
    opt.ROI (1,4) double
    opt.RefFileName = ''
end

if isa(opt.lambda,'Illumination')
    opt.lambda = opt.lambda.lambda*1e9;
else
    opt.lambda = opt.lambda*1e9;
end

if isempty(opt.expTime)
    opt.expTime = Itf.expTime;
end

t = Tiff(fileName, 'w');

tagstruct.DateTime = datetime2str(Itf.timeStamp);

if ~isfield(opt,'ROI')
    opt.ROI = [1 1 Itf.Nx Itf.Ny];
end
tagstruct.Make = ROI2str(opt.ROI);

description = sprintf([...
'\nACQUISITION\n', ...
'  Exposure time:\t%d\n', ...
'  Number of average images:\t%d\n', ...
'ILLUMINATION\n', ...
'  lambda:\t%d nm\n', ...
'MICROSCOPE\n', ...
'  Microscope magnification:\t%d x\n', ...
'  Objective magnification:\t%d x\n', ...
'  NA:\t%g\n', ...
'  Tubelens focal length\t%d cm\n', ...
'  CGcamera name:\t%s', ...
'  Relaylens model:\t%s', ...
'  Crossgrating name:\t%s', ...
'  Camera model:\t%s', ...
'  CG distance:\t%d mm\n', ...
'  Zoom:\t%d x\n', ...
'  Dexel size:\t%g µm\n', ...
'  Pixel size:\t%g nm\n', ...
'  Zeta:\t%d\n', ...
'  Gamma:\t%d µm\n'], ...
Itf.expTime, ...
Itf.Navg, ...
opt.lambda, ...
MI.M, ...
MI.Objective.Mobj, ...
MI.Objective.NA, ...
MI.f_TL, ...
MI.CGcam.fileName, ...
MI.CGcam.RL.model, ...
MI.CGcam.CG.name, ...
MI.CGcam.Camera.model, ...
MI.CGcam.CGpos*1e3, ...
MI.CGcam.zoom, ...
MI.CGcam.Camera.dxSize*1e6, ...
MI.pxSize*1e9, ...
MI.CGcam.zeta, ...
MI.CGcam.CG.Gamma*1e6);

tagstruct.ImageDescription = description;

    tagstruct.ImageLength = Itf.Ny;
    tagstruct.ImageWidth = Itf.Nx;
    tagstruct.Photometric = Tiff.Photometric.MinIsBlack;
    tagstruct.BitsPerSample = 16;
    % tagstruct.SamplesPerPixel = 1;
    % tagstruct.RowsPerStrip = 16;
    tagstruct.PlanarConfiguration = Tiff.PlanarConfiguration.Chunky;
    % tagstruct.ImageDescription = description;
    % tagstruct.Model = description;
    % tagstruct.Make = description;
    % tagstruct.Artist = description;
    % tagstruct.Copyright = description;
    % tagstruct.Software = description;
    tagstruct.HostComputer = opt.RefFileName;
    % tagstruct.DateTime = '20jan2025';



t.setTag(tagstruct);
t.write(uint16(Itf(1).Itf));
t.close();
end